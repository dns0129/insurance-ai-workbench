from pathlib import Path
import atexit, os, subprocess, tempfile
from playwright.sync_api import sync_playwright, expect

root=Path(__file__).resolve().parents[1]
out=root/'test-results'/'visual-upgrade'
out.mkdir(parents=True,exist_ok=True)
tmp=tempfile.TemporaryDirectory(prefix='insurance-ui-')
code="import {createApp} from './server.mjs';const {server}=createApp({dbPath:process.env.DB_PATH,env:{}});server.listen(0,'127.0.0.1',()=>console.log('http://127.0.0.1:'+server.address().port));"
server=subprocess.Popen(['/usr/local/bin/node','--input-type=module','-e',code],cwd=root,env={**os.environ,'DB_PATH':str(Path(tmp.name)/'test.sqlite')},stdout=subprocess.PIPE,text=True)
def cleanup():
    server.terminate()
    server.wait(timeout=5)
    tmp.cleanup()
atexit.register(cleanup)
base=server.stdout.readline().strip()
assert base.startswith('http://127.0.0.1:'),base
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless=True)
    page=browser.new_page(viewport={'width':1440,'height':1050},device_scale_factor=1)
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.goto(base,wait_until='networkidle')
    page.evaluate('document.fonts.ready')
    expect(page.locator('#login-agent option')).to_have_count(3)
    page.screenshot(path=str(out/'login.png'),full_page=True)
    page.locator('#login-submit').click()
    expect(page.locator('.member-card')).to_have_count(3)
    expect(page.locator('.member-card.warn')).to_have_count(1)
    expect(page.locator('#chart svg')).to_have_attribute('aria-label',__import__('re').compile('月目标¥300,000'))
    page.screenshot(path=str(out/'leader.png'),full_page=True)
    page.locator('.rowlink[data-agent="A006"]').click()
    expect(page.locator('#chart svg')).to_have_attribute('aria-label',__import__('re').compile('林晓'))
    page.locator('.chart-values summary').click()
    expect(page.locator('#chart-data tbody tr')).to_have_count(6)
    page.locator('#main-nav [data-nav="policies"]').click()
    expect(page.locator('#policies')).to_be_visible()
    expect(page.locator('#policy-agent')).to_have_value('A006')
    expect(page.locator('#policies tbody tr')).to_have_count(5)
    page.locator('#policy-agent').select_option('')
    expect(page.locator('#policies tbody tr')).to_have_count(10)
    page.screenshot(path=str(out/'policies.png'),full_page=True)
    page.locator('#add-policy').click()
    expect(page.locator('#entry-client option')).to_have_count(30)
    page.locator('#entry-agent').select_option('A006')
    expect(page.locator('#entry-client option').first).to_have_attribute('value','A006C01')
    page.screenshot(path=str(out/'entry.png'),full_page=True)
    page.locator('#entry-form [name="id"]').fill('UI-UPGRADE-QA-20261107')
    page.locator('#entry-form [name="premium"]').fill('12.34')
    page.locator('#entry-save').click()
    expect(page.locator('#io-collect')).not_to_be_visible()
    expect(page.locator('#policies tbody tr')).to_have_count(6)
    page.locator('#main-nav [data-nav="ai"]').click()
    page.locator('[data-question="目标差距"]').click()
    expect(page.locator('#ai-answer')).to_contain_text('【模拟分析】')
    page.locator('#notice').evaluate('(e)=>e.hidden=true')
    page.screenshot(path=str(out/'ai.png'),full_page=True)
    page.locator('#main-nav [data-nav="overview"]').click()
    for width in [1024,768,375,320]:
        page.set_viewport_size({'width':width,'height':1050})
        page.wait_for_timeout(100)
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'),f'overflow {width}'
        assert page.locator('.stat').evaluate_all('(els)=>els.every(e=>e.scrollWidth<=e.clientWidth)'),f'stat overflow {width}'
    page.set_viewport_size({'width':375,'height':900})
    page.screenshot(path=str(out/'mobile.png'),full_page=True)
    page.set_viewport_size({'width':1440,'height':1050})
    page.locator('#switch-account').click()
    page.locator('[name="role"][value="agent"]').check()
